import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const bridgeDir = path.resolve(here, '..');
// 생성물은 항상 이 브리지가 속한 애드온의 generated/에 쓴다.
// AIT_ADDON_DIR이 있으면 그 애드온을, 없으면 파일 위치 기준
// tools/bridge/scripts → tools/bridge → tools → addons/apps_in_toss로 거슬러
// 올라간 애드온을 쓴다. env 없이 `npm run generate`(prepare)를 실행해도
// 엉뚱한 tools/addons/... 경로에 생성물이 생기지 않는다.
const sdkDir = process.env.AIT_ADDON_DIR
  ? path.resolve(process.env.AIT_ADDON_DIR)
  : path.resolve(bridgeDir, '..', '..');
const manifest = JSON.parse(fs.readFileSync(path.join(bridgeDir, 'api-manifest.json'), 'utf8'));
const generatedDir = path.join(sdkDir, 'generated');
fs.mkdirSync(generatedDir, { recursive: true });
const out = path.join(generatedDir, 'ait_generated_api.gd');

const lines = [
  '# AUTO-GENERATED by bridge/scripts/generate-gdscript.mjs. Do not edit.',
  'extends RefCounted',
  'class_name AITGeneratedAPI',
  '',
  'var _core: AITCore',
  '',
  'func _init(core: AITCore) -> void:',
  '    _core = core',
  '',
];

for (const api of manifest) {
  const params = api.args.map((a) => `${a}: Variant`).join(', ');
  const args = api.args.join(', ');
  lines.push(`func ${api.name}(${params}) -> int:`);
  lines.push(`    return _core.invoke(${JSON.stringify(api.path)}, [${args}])`);
  lines.push('');
}

// Unity SDK의 APITestCatalog.cs에 대응하는 카탈로그 단일 소스.
// 인터랙티브/자동 테스터가 api-manifest.json을 직접 소비할 수 있게 생성한다.
const catalog = [
  '# AUTO-GENERATED by bridge/scripts/generate-gdscript.mjs. Do not edit.',
  'class_name AITGeneratedCatalog',
  '',
  'const APIS: Array[Dictionary] = [',
];
for (const api of manifest) {
  catalog.push(`\t{"name": "${api.name}", "path": "${api.path}", "args": ${JSON.stringify(api.args)}},`);
}
catalog.push(']', '');
fs.writeFileSync(path.join(generatedDir, 'ait_generated_catalog.gd'), catalog.join('\n'));

fs.writeFileSync(out, lines.join('\n'));
console.log(`Generated ${out} (${manifest.length} APIs)`);
console.log(`Generated ${path.join(generatedDir, 'ait_generated_catalog.gd')} (catalog)`);
